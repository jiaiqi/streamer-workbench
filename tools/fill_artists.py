def main() -> None:
    lib = build_default_library(json_path="data/songs.json")
    filled, kept, unknown = [], [], []
    for s in lib.songs:
        if s.artists:
            kept.append(s.title)          # 已有值，不动
        elif s.title in ARTISTS:
            s.artists = ARTISTS[s.title]
            filled.append(s.title)
        else:
            unknown.append(s.title)       # 低置信度，留空待手工补
    lib.save("data/songs.json", backup_dir="data/backups")
    print(f"回填 {len(filled)} 首 · 已有值保留 {len(kept)} 首 · 留空待补 {len(unknown)} 首")
    if unknown:
        print("\n留空清单（请主播在编辑界面补）：")
        print("、".join(unknown))


if __name__ == "__main__":
    main()
